if __name__ == "__main__":
    out = os.path.join(os.path.dirname(__file__), "..", "public", "sprites", "font.png")
    im = Image.new("RGBA", (CELL_W * len(FONT_CHARS), CELL_H), (0, 0, 0, 0))
    px = im.load()
    for i, ch in enumerate(FONT_CHARS):
        rows = G[ch]
        for y, bits in enumerate(rows):
            for x in range(5):
                if bits & (0x10 >> x):
                    px[i * CELL_W + x, y] = (255, 255, 255, 255)
    im.save(out)
    print(f"font: {len(FONT_CHARS)} glyphs, {im.size[0]}x{im.size[1]} -> {out}")
